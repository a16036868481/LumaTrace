import { localeCatalog } from "./localeCatalog";

export type Locale = (typeof localeCatalog)[number]["locale"];
const localeModules = import.meta.glob("./locales/*.json", {
  import: "default"
}) as Record<string, () => Promise<Record<string, string>>>;
const packagedLocaleIds = new Set(
  Object.keys(localeModules).map((path) => path.slice("./locales/".length, -".json".length))
);

// The catalog tracks every planned language. Only dictionaries that have been
// directly localized and packaged are exposed in the selector; a missing file
// must never silently masquerade as a translated locale through English fallback.
export const locales = localeCatalog
  .filter((entry) => packagedLocaleIds.has(entry.locale))
  .map((entry) => entry.locale) as Locale[];

function nativeLocaleLabel(entry: (typeof localeCatalog)[number]): string {
  if (entry.locale === "en-US" || entry.label !== entry.englishName) {
    return entry.label;
  }
  try {
    if (Intl.DisplayNames.supportedLocalesOf([entry.locale]).length === 0) {
      return entry.label;
    }
    const label = new Intl.DisplayNames([entry.locale], {
      type: "language",
      fallback: "none"
    }).of(entry.locale);
    return label?.trim() || entry.label;
  } catch {
    return entry.label;
  }
}

export const localeLabels = Object.fromEntries(
  localeCatalog.map((entry) => [entry.locale, nativeLocaleLabel(entry)])
) as Record<Locale, string>;
export const localeEnglishNames = Object.fromEntries(
  localeCatalog.map((entry) => [entry.locale, entry.englishName])
) as Record<Locale, string>;
export const rtlLocales = new Set<Locale>(
  localeCatalog.filter((entry) => entry.direction === "rtl").map((entry) => entry.locale)
);
