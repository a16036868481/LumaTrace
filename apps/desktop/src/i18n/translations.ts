export type TranslationDictionary = Record<TranslationKey, string>;
export const defaultTranslations: TranslationDictionary = enUS;
const translationCache = new Map<Locale, TranslationDictionary>([["en-US", defaultTranslations]]);

function validateDictionary(locale: Locale, value: Record<string, string>): TranslationDictionary {
  const expectedKeys = Object.keys(defaultTranslations);
  const receivedKeys = Object.keys(value);
  const templateTokens = (text: string) =>
    [...text.matchAll(/\{[a-zA-Z0-9_]+\}/g)].map((match) => match[0]).sort();
  if (receivedKeys.length !== expectedKeys.length) {
    throw new Error(
      `Invalid translations for ${locale}: expected ${expectedKeys.length} keys, received ${receivedKeys.length}`
    );
  }
  for (const key of expectedKeys) {
    if (typeof value[key] !== "string" || value[key].trim().length === 0) {
      throw new Error(`Invalid translations for ${locale}: ${key} is missing or empty`);
    }
    if (
      templateTokens(value[key]).join("\0") !==
      templateTokens(defaultTranslations[key as TranslationKey]).join("\0")
    ) {
      throw new Error(
        `Invalid translations for ${locale}: ${key} changed its template placeholders`
      );
    }
  }
  return value as TranslationDictionary;
}

export function getCachedTranslations(locale: Locale): TranslationDictionary | undefined {
  return translationCache.get(locale);
}

export async function loadTranslations(locale: Locale): Promise<TranslationDictionary> {
  const cached = translationCache.get(locale);
  if (cached !== undefined) {
    return cached;
  }
  const loader = localeModules[`./locales/${locale}.json`];
  if (loader === undefined) {
    throw new Error(`Missing translations for ${locale}`);
  }
  const dictionary = validateDictionary(locale, await loader());
  translationCache.set(locale, dictionary);
  return dictionary;
}
